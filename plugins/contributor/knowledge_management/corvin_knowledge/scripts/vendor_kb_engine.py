#!/usr/bin/env python3
"""Copy the kb engine from a Corvin-Knowledge checkout into src/kb_engine/.

The engine (`kb.py` + `kb_lib.py` + `kb_model.py`) is authored in Corvin-Knowledge, which is
a private repository. A fresh CorvinOS install can only reach this public marketplace, so the
plugin carries a byte-identical copy and records where it came from in ENGINE.json
(source commit + sha256 per file). `tests/test_tenant_kb.py` fails when a file no longer
matches ENGINE.json, so a hand edit of the copy cannot ship unnoticed.

    python3 scripts/vendor_kb_engine.py [--source /path/to/Corvin-Knowledge]

Refuses a source whose engine files have uncommitted changes: the recorded commit must be
the code that was copied.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ENGINE_FILES = ("kb.py", "kb_lib.py", "kb_model.py")
HERE = Path(__file__).resolve().parents[1]
DEST = HERE / "src" / "kb_engine"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source", default=str(HERE.parents[4] / "Corvin-Knowledge"))
    a = ap.parse_args()
    src = Path(a.source).resolve() / "scripts"
    missing = [f for f in ENGINE_FILES if not (src / f).is_file()]
    if missing:
        print(f"no kb engine at {src} (missing {missing})", file=sys.stderr)
        return 2
    dirty = subprocess.run(["git", "-C", str(src.parent), "status", "--porcelain", "--",
                            *[f"scripts/{f}" for f in ENGINE_FILES]], capture_output=True, text=True).stdout
    if dirty.strip():
        print(f"refused: uncommitted engine changes in {src.parent}:\n{dirty}", file=sys.stderr)
        return 2
    commit = subprocess.run(["git", "-C", str(src.parent), "rev-parse", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()
    DEST.mkdir(parents=True, exist_ok=True)
    files = {}
    for f in ENGINE_FILES:
        shutil.copyfile(src / f, DEST / f)
        files[f] = hashlib.sha256((DEST / f).read_bytes()).hexdigest()
    manifest = {
        "note": "generated by scripts/vendor_kb_engine.py — do not edit the engine files by hand",
        "source_repo": "CorvinLabs/Corvin-Knowledge",
        "source_commit": commit,
        "files": files,
    }
    (DEST / "ENGINE.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"vendored": list(files), "source_commit": commit[:12]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
